"""Generate two evidence reports from saved run artifacts (no model calls):
  docs/run_table.md   - every run: date, mode, counts, elapsed time, known cost, coverage
  docs/claim_trace.md - one published claim traced to brief, decision, stored version and passage
Usage: python docs/make_reports.py APPROVED_RUN_DIR CLAIM_ID   (e.g. runs/replay-... 02-c1)"""
import glob, json, os, re, subprocess, sys

approved, claim_id = sys.argv[1], sys.argv[2]


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def jsonl(p):
    return [json.loads(l) for l in open(p) if l.strip()] if os.path.exists(p) else []


# ---------- run table ----------
rows = ["| Run | Mode | As-of date | Discovered | New / changed / unchanged | Eligible / excluded | "
        "Accept / reject / defer | Elapsed | Known cost (USD) | Notes |",
        "|---|---|---|---|---|---|---|---|---|---|"]
for d in sorted(glob.glob("runs/*/"), key=lambda p: load(p + "run.json")["started_at"]):
    s, r = load(d + "summary.json"), load(d + "run.json")
    if not s or not r:
        continue
    c = s["counts"]
    notes = []
    if r.get("simulated_failure"):
        notes.append(f"LABELLED SIMULATED FAILURE: {r['simulated_failure']['source_id']}")
    if r.get("replay_of"):
        notes.append(f"replay of {r['replay_of']} (no recollection)")
    if s.get("collection") and not s["collection"].get("complete", True):
        notes.append("incomplete coverage: " + ", ".join(s["collection"]["problems"]))
    if s.get("published_links"):
        notes.append("PUBLISHED SERIES")
    el = s.get("elapsed_seconds")
    rows.append(f"| `{d.rstrip('/')}` | {r['mode']} | {r['as_of_date']} | {c['discovered']} | "
                f"{c['new']} / {c['changed']} / {c['unchanged']} | {c['eligible']} / {c['excluded']} | "
                f"{c['accepted']} / {c['rejected']} / {c['deferred']} | "
                f"{'%d min' % round(el / 60) if el else 'n/a'} | {s.get('cost_usd_known')} | {'; '.join(notes)} |")
rows.append("")
rows.append("Known cost = Whisper transcription (computed from audio minutes). Model calls (gpt-5.4-mini, gpt-5.5) "
            "are logged with token counts in each run's llm_calls/ but priced as unknown because no prices are set in "
            "config/models.json. Replay rows reuse the source run's collection counts.")
open("docs/run_table.md", "w").write("# Runs\n\nGenerated by docs/make_reports.py from each run's run.json and summary.json.\n\n"
                                     + "\n".join(rows) + "\n")

# ---------- claim trace ----------
pid = claim_id.split("-")[0]
brief = next(b for b in jsonl(f"{approved}/briefs.jsonl") if b["piece_id"] == pid)
claim = next(c for c in brief["claims"] if c["claim_id"] == claim_id)
decisions = {d["item_id"]: d for d in jsonl(f"{approved}/decisions.jsonl")}
links = {l["piece_id"]: l for l in (load(f"{approved}/package/publication_links.json") or [])}
article = open(f"{approved}/package/articles/{pid}.md", encoding="utf-8").read().split("## Sources")[0]
sentences = [s.strip() for line in article.splitlines() if not line.startswith("#")
             for s in re.split(r"(?<=[.!?\]])\s+(?=[A-Z\"*])", line) if f"[{claim_id}]" in s]

out = [f"# Claim trace: {claim_id}", "",
       f"Approved run: `{approved}`. Published article: {links.get(pid, {}).get('substack_url')} · "
       f"video: {links.get(pid, {}).get('youtube_url')}", "",
       "## 1. Published sentence(s)", ""] + [f"> {s}" for s in sentences[:3]] + [
       "", f"## 2. Claim in the brief (`{approved}/briefs.jsonl`, piece {pid})", "",
       f"- **{claim_id}** ({claim['type']}): {claim['statement']}", "", "## 3. Evidence", ""]
for ref in claim["evidence"]:
    r = subprocess.run(["bash", "data/store.sh", "get", ref["item_id"], ref["version_id"]], capture_output=True, text=True)
    item = json.loads(r.stdout) if r.returncode == 0 else None
    d = decisions.get(ref["item_id"], {})
    out += [f"### `{ref['item_id']}`",
            f"- Editorial decision: **{d.get('decision')}** by {d.get('decided_by', 'model')} for pieces {d.get('piece_ids')}: {d.get('reason', '')}"]
    if not item:
        out += ["- (version not found in store)", ""]
        continue
    out += [f"- Source: {item['publisher_id']}, \"{item['title']}\", published {item['published_at']}, retrieved {item['retrieved_at']}",
            f"- URL: {item['url']}",
            f"- Stored version: `{ref['version_id']}` (store: `bash data/store.sh get {ref['item_id']} {ref['version_id']}`)",
            f"- Retained text: `{item['text_path']}`" + (f"; segments: `{item['segments_path']}`" if item.get("segments_path") else "")]
    loc = ref["locator"]
    if loc["type"] == "text":
        out += [f"- Exact passage (verified verbatim by review/check_content.sh):", f"  > {loc['quote']}"]
    else:
        seg = next((s for s in json.load(open(item["segments_path"])) if s["segment_id"] == loc["segment_id"]), None)
        if seg:
            t = int(seg["start_seconds"])
            link = f"{item['url']}&t={t}s" if item["kind"] == "youtube" else item["url"]
            out += [f"- Segment `{loc['segment_id']}` at {t // 60}:{t % 60:02d}-{int(seg['end_seconds']) // 60}:{int(seg['end_seconds']) % 60:02d} ({link}):",
                    f"  > {seg['text']}"]
    out.append("")
open("docs/claim_trace.md", "w").write("\n".join(out) + "\n")
print("wrote docs/run_table.md and docs/claim_trace.md")
